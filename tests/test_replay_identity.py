def test_metadata_is_outside_the_artifact_identity():
    """A value the identity does not cover can be edited without changing it."""
    from rh_research_engine.contracts.artifacts import PropertyAssertion

    base = dict(
        artifact_id="A-1",
        created_by="rh-math-worker",
        method_family="python",
        method_version="0.11.0",
        object_id="obj",
        property_kind="bound",
        value="X^0.4",
    )
    plain = PropertyAssertion(**base)
    annotated = PropertyAssertion(**base, metadata={"reviewed_by": "someone"})
    assert plain.artifact_hash() == annotated.artifact_hash()
    assert "metadata" not in json.loads(plain.canonical_json())


def test_a_favourable_verdict_written_into_metadata_changes_nothing():
    """Closure re-resolves every run; there is no cached verdict to poison."""
    premise = _circular_premise().model_copy(
        update={"metadata": {"advances_frontier": True, "discharge_receipts": {"OBL-1": "x"}}}
    )
    graph = implication_closure(
        PropertyGraph(properties=[premise]), mode=ClosureMode.RIGOROUS
    )
    assert [p.id for p in graph.properties] == ["P-EQ"]


