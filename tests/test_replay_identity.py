#: Everything a reader needs to re-check a discharge without the registries.
REQUIRED_PROVENANCE_FIELDS = {
    "obligation_ref",
    "obligation_hash",
    "evidence_refs",
    "evidence_hashes",
    "discharged_direction",
    "requirements_satisfied",
    "decision_ref",
    "decision_hash",
    "receipt_ref",
    "receipt_hash",
    "dre_engine_fingerprint",
    "dre_model_pack_hash",
    "dre_input_hash",
    "dre_proof_hash",
    "receipt_authentication",
}


def _accepted_resolution():
    obligations, evidence, decisions, receipts = helpers_discharge.accepted_registry()
    with helpers_discharge.trusting_test_engine(receipts.values()):
        return resolve_discharges(
            ["OBL-1"],
            obligations=obligations,
            evidence=evidence,
            decisions=decisions,
            receipts=receipts,
        )


def test_a_qualifying_discharge_carries_its_full_replay_identity():
    resolution = _accepted_resolution()
    assert resolution.qualifying == ["OBL-1"]
    payload = resolution.provenance_payload()["OBL-1"]
    assert set(payload) == REQUIRED_PROVENANCE_FIELDS
    assert payload["dre_engine_fingerprint"] == helpers_discharge.TEST_ENGINE
    assert payload["receipt_authentication"] == "signature"


def test_a_refused_discharge_carries_no_provenance():
    """Provenance is evidence of authority, so it exists only where authority does."""
    resolution = resolve_discharges(
        ["OBL-1"], **dict(zip(
            ("obligations", "evidence", "decisions", "receipts"),
            helpers_discharge.accepted_registry(),
            strict=True,
        ))
    )
    assert resolution.qualifying == []
    assert resolution.provenance_payload() == {}


def _circular_premise() -> PropertyRecord:
    return PropertyRecord(
        id="P-EQ",
        object_id="obj",
        kind=PropertyKind.GROWTH_BOUND,
        value="X^0.4",
        status=EpistemicStatus.KNOWN,
        provenance=[Provenance(source_type="knowledge", source_id="K", method="m")],
        role=MathematicalRole.EQUIVALENCE,
        rh_equivalent=True,
        discharged_obligations=["OBL-1"],
    )


def test_closure_persists_the_discharge_provenance_into_the_graph():
    """Held only in the caller's registries, none of this survives the run.

    A reader of the stored graph would otherwise see a rigorous derived bound
    whose premise restates RH, with nothing recording why that was allowed.
    """
    obligations, evidence, decisions, receipts = helpers_discharge.accepted_registry()
    with helpers_discharge.trusting_test_engine(receipts.values()):
        graph = implication_closure(
            PropertyGraph(properties=[_circular_premise()]),
            mode=ClosureMode.RIGOROUS,
            obligations=obligations,
            evidence=evidence,
            decisions=decisions,
            receipts=receipts,
        )
    derived = [p for p in graph.properties if p.id != "P-EQ"]
    assert derived, "the discharge should have unlocked the rule"
    provenance = derived[0].metadata["discharge_provenance"]["OBL-1"]
    assert set(provenance) == REQUIRED_PROVENANCE_FIELDS
    assert derived[0].metadata["premise_hash"] == _circular_premise().record_hash()

    # And it survives serialization: a transient registry is not provenance.
    round_tripped = json.loads(json.dumps(graph.model_dump(mode="json")))
    stored = [p for p in round_tripped["properties"] if p["id"] != "P-EQ"][0]
    assert set(stored["metadata"]["discharge_provenance"]["OBL-1"]) == (
        REQUIRED_PROVENANCE_FIELDS
    )


