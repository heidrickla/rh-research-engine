"""Canonical identity, complete provenance, and determinism.

A replay record that cannot be regenerated byte-for-byte is not a replay
record. Three things have to hold for that: one serialization per artifact, a
digest that actually is a digest, and provenance complete enough that the
decision can be re-checked from the stored record alone rather than from a
registry that vanished when the process exited.
"""

