# 8.4  Determinism across processes and hash seeds
# ---------------------------------------------------------------------------

_HASH_SCRIPT = """
import json, sys
sys.path.insert(0, %r)
sys.path.insert(0, %r)
from helpers_discharge import accepted_registry
obligations, evidence, decisions, receipts = accepted_registry()
print(json.dumps({
    "obligation": obligations["OBL-1"].artifact_hash(),
    "evidence": evidence["EV-1"].artifact_hash(),
    "decision": decisions["OBL-1"].artifact_hash(),
    "receipt": receipts["DEC-1"].receipt_hash(),
}))
"""


@pytest.mark.parametrize("seed", ["0", "1", "12345"])
def test_artifact_identity_is_independent_of_the_hash_seed(seed):
    """Set and dict iteration order is seeded per interpreter.

    In-process tests cannot catch anything seeded that way, because they all
    share one interpreter. Separate invocations under different seeds can.
    """
    script = _HASH_SCRIPT % (str(REPO / "src"), str(REPO / "tests"))
    result = subprocess.run(
        [sys.executable, "-c", script],
        capture_output=True,
        text=True,
        encoding="utf-8",
        env={"PYTHONHASHSEED": seed, "PATH": "", "SYSTEMROOT": ""},
    )
    assert result.returncode == 0, result.stderr
    hashes = json.loads(result.stdout)
    assert hashes == {
        "obligation": hashes["obligation"],
        "evidence": hashes["evidence"],
        "decision": hashes["decision"],
        "receipt": hashes["receipt"],
    }
    # Compare against the in-process values, which is the actual invariant.
    obligations, evidence, decisions, receipts = helpers_discharge.accepted_registry()
    assert hashes["obligation"] == obligations["OBL-1"].artifact_hash()
    assert hashes["evidence"] == evidence["EV-1"].artifact_hash()
    assert hashes["decision"] == decisions["OBL-1"].artifact_hash()
    assert hashes["receipt"] == receipts["DEC-1"].receipt_hash()


def test_the_same_inputs_produce_the_same_closure_output():
    """Two runs over identical inputs must agree on every byte."""
    obligations, evidence, decisions, receipts = helpers_discharge.accepted_registry()
    outputs = []
    for _ in range(2):
        with helpers_discharge.trusting_test_engine(receipts.values()):
            outputs.append(
                implication_closure(
                    PropertyGraph(properties=[_circular_premise()]),
                    mode=ClosureMode.RIGOROUS,
                    obligations=obligations,
                    evidence=evidence,
                    decisions=decisions,
                    receipts=receipts,
                ).graph_hash()
            )
    assert outputs[0] == outputs[1]


def test_an_unauthenticated_receipt_is_refused_even_from_a_trusted_engine():
    """The activation requirement, enforced rather than documented.

    A fingerprint names the *claimed* issuer, and the claim travels inside the
    receipt. Registering one is necessary and not sufficient.
    """
    registry = helpers_discharge.unauthenticated_receipt_registry()
    with helpers_discharge.trusting_registry(registry):
        resolution = resolve_discharges(
            ["OBL-1"], **dict(zip(
                ("obligations", "evidence", "decisions", "receipts"),
                registry,
                strict=True,
            ))
        )
    assert resolution.qualifying == []
    assert "receipt_authentication" in resolution.explain()
    assert ReceiptAuthentication.NONE.value in resolution.explain()
