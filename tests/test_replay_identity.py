# 3.4  EXPLORATORY relaxes rigour, never circularity
# ---------------------------------------------------------------------------


def test_exploratory_mode_relaxes_rigour():
    """A non-rigorous premise may drive a heuristic conclusion."""
    premise = PropertyRecord(
        id="P-SOFT",
        object_id="obj",
        kind=PropertyKind.GROWTH_BOUND,
        value="X^0.4",
        status=EpistemicStatus.SYMBOLIC_DERIVED,
        provenance=[Provenance(source_type="symbolic", source_id="s", method="m")],
        role=MathematicalRole.BOUND,
    )
    rigorous = implication_closure(
        PropertyGraph(properties=[premise]), mode=ClosureMode.RIGOROUS
    )
    exploratory = implication_closure(
        PropertyGraph(properties=[premise]), mode=ClosureMode.EXPLORATORY
    )
    assert [p.id for p in rigorous.properties] == ["P-SOFT"]
    derived = [p for p in exploratory.properties if p.id != "P-SOFT"]
    assert derived, "exploratory mode should relax the rigour requirement"
    assert derived[0].status is EpistemicStatus.HEURISTIC


def test_exploratory_mode_does_not_relax_circularity():
    """The relaxation is on confidence only.

    An undischarged RH-equivalent premise is not `frontier_relevant`, and
    exploratory mode still requires that. Otherwise the mode intended for
    loosening rigour would quietly re-enable the circular step the whole layer
    exists to block.
    """
    graph = implication_closure(
        PropertyGraph(properties=[_circular_premise()]), mode=ClosureMode.EXPLORATORY
    )
    assert [p.id for p in graph.properties] == ["P-EQ"]


