def test_canonical_json_is_order_independent():
    """Key order is the commonest source of a digest that will not reproduce."""
    assert canonical_json({"b": 1, "a": 2}) == canonical_json({"a": 2, "b": 1})
    assert canonical_hash({"b": 1, "a": 2}) == canonical_hash({"a": 2, "b": 1})


def test_canonical_json_leaves_no_whitespace_to_drift():
    assert canonical_json({"a": 1, "b": [1, 2]}) == '{"a":1,"b":[1,2]}'


def test_canonical_json_keeps_mathematical_notation_as_itself():
    """`ensure_ascii=False`: escape spellings vary between encoders."""
    assert canonical_json({"k": "θ <= 1/2"}) == '{"k":"θ <= 1/2"}'


def test_a_receipt_hash_is_canonical_json_not_concatenation():
    """Joining fields with a delimiter is ambiguous and positional.

    A field containing the delimiter shifts the boundary, so two different
    receipts can produce one string; and adding a field silently redefines the
    digest without changing its shape.
    """
    _, _, decisions, receipts = helpers_discharge.accepted_registry()
    receipt = receipts["DEC-1"]
    assert receipt.receipt_hash() == canonical_hash(receipt.model_dump(mode="json"))
    assert receipt.receipt_hash() == receipt.model_copy().receipt_hash()

    # Changing any field changes the identity.
    altered = receipt.model_copy(update={"dre_input_hash": "f" * 64})
    assert altered.receipt_hash() != receipt.receipt_hash()
    assert decisions  # the registry is wired up; not an empty-input pass


@pytest.mark.parametrize(
    "field",
    ["dre_decision_hash", "dre_input_hash", "dre_model_pack_hash", "dre_proof_hash"],
)
@pytest.mark.parametrize(
    "bad", ["", "pending", "A" * 64, "a" * 63, "a" * 65, "g" * 64], ids=range(6)
)
def test_a_hash_field_must_hold_a_hash(field, bad):
    """Uppercase is rejected rather than normalized.

    Two spellings of one digest is two identities for one artifact, and the
    comparison that matters is done on the raw string.
    """
    fields = dict(
        decision_ref="DEC-1",
        dre_decision_hash="a" * 64,
        dre_input_hash="b" * 64,
        dre_model_pack_hash="c" * 64,
        dre_engine_fingerprint="engine@1",
        dre_proof_hash="d" * 64,
    )
    fields[field] = bad
    with pytest.raises(pydantic.ValidationError, match="64 lowercase hexadecimal"):
        DreReceipt(**fields)


